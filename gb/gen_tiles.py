#!/usr/bin/env python3
"""Generate tiles.h (2bpp Game Boy tile data + indices) for flappy.c."""

FONT = {
 '0':'75557','1':'26227','2':'71747','3':'71717','4':'55711','5':'74717','6':'74757','7':'71111','8':'75757','9':'75717',
 'A':'25755','B':'65656','C':'34443','D':'65556','E':'74647','F':'74644','G':'34553','H':'55755','I':'72227','J':'11152',
 'K':'55655','L':'44447','M':'57755','N':'65555','O':'25552','P':'65644','Q':'25531','R':'65655','S':'34216','T':'72222',
 'U':'55557','V':'55552','W':'55775','X':'55255','Y':'55222','Z':'71247','-':'00700','x':'05250','!':'22202',
}

def glyph(rows):
    out = ['........'] * 1
    for r in rows:
        b = int(r)
        line = '.'
        for k in range(3):
            line += '##' if b & (4 >> k) else '..'
        out.append((line + '.' * 8)[:8])
    out += ['........'] * (8 - len(out))
    return out

ART = {
 'PIPE_BODYL': ['#aabbbbb'] * 8,
 'PIPE_BODYR': ['bbbbbbb#'] * 8,
 'PIPE_CAPL': ['########'] + ['#aabbbbb'] * 6 + ['########'],
 'PIPE_CAPR': ['########'] + ['bbbbbbb#'] * 6 + ['########'],
 'GROUND': ['########','abbbbbb#','abbbbbb#','abbbbbb#','########','bbb#abbb','bbb#abbb','########'],
 'FLAGTOP': ['..####..','...##...','...##bbb','...##bb.','...##b..','...##...','...##...','...##...'],
 'POLE': ['...##...'] * 8,
 'CLOUDL': ['........','......##','.....#aa','...##aaa','..#aaaaa','..#aaaaa','.#aaaaaa','########'],
 'CLOUDR': ['........','##......','aa#.....','aaa##...','aaaaa#..','aaaaa#..','aaaaaa#.','########'],
 'BIRD0': ['..####..','.#aaaa#.','#aaa.#a#','#bbaaaa#','#bbaa###','.#aaaa#.','..####..','........'],
 'BIRD1': ['..####..','.#aaaa#.','#aaa.#a#','#aaaaaa#','#aaaa###','.#bbaa#.','..####..','........'],
 'COIN0': ['..####..','.#aaaa#.','#abbbba#','#abbbba#','#abbbba#','#abbbba#','.#aaaa#.','..####..'],
 'COIN1': ['...##...','...##...','..#ab#..','..#ab#..','..#ab#..','..#ab#..','...##...','...##...'],
}
CH = {'.': 0, 'a': 1, 'b': 2, '#': 3, '0': 0}

def enc(rows):
    out = []
    for r in rows:
        lo = hi = 0
        for i, c in enumerate(r):
            v = CH[c]
            lo |= (v & 1) << (7 - i)
            hi |= (v >> 1) << (7 - i)
        out += [lo, hi]
    return out

tiles, names = [enc(['........'] * 8)], {'BLANK': 0}
for ch in '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-x!':
    names['F_' + ch] = len(tiles); tiles.append(enc(glyph(FONT[ch])))
for k, v in ART.items():
    names[k] = len(tiles); tiles.append(enc(v))

with open('tiles.h', 'w') as f:
    f.write('/* generated by gen_tiles.py */\n')
    for k, v in names.items():
        if k.startswith('F_'):
            continue
        f.write('#define T_%s %d\n' % (k, v))
    f.write('#define T_0 %d\n#define T_A %d\n#define T_DASH %d\n#define T_X %d\n#define T_BANG %d\n' %
            (names['F_0'], names['F_A'], names['F_-'], names['F_x'], names['F_!']))
    f.write('#define NTILES %d\n' % len(tiles))
    f.write('static const unsigned char tiledata[] = {\n')
    for t in tiles:
        f.write(' ' + ','.join('0x%02x' % b for b in t) + ',\n')
    f.write('};\n')
print(len(tiles), 'tiles')
